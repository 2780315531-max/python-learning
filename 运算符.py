#算术运算符：+ - / *   //   %   **
print("10 + 4 =",10 + 4)
print("10 - 4 =",10 - 4)
print("10 * 4 =",10 * 4)
print("10 / 4 =",10 / 4)
print("10 // 4 =",10 // 4) #整除（结果为整数）
print("10 % 4 =",10 % 4)  #取余/求模
print("10 ** 4 =",10 ** 4) # 10的4次方，幂指数

#算术运算符的优先级---> ** -->*    /  //    %  -->+ -
print("0.1 + 10 / 4 ** 2 =", 0.1 + 10 / 4 ** 2)

#案例1:要求输入两个数x与y，分别输出x+y和x-y的结果
#float(..)--->将其他类型转为浮点数类型
x = float(input("输入x的数:"))
y = float(input("输入y的数:"))
print("x + y=",x + y)
print("x - y=", x - y)


