#定义字符串的三种方式
s1 = "Hello"  #双引号定义
s2 = 'Python'  #单引号定义
s3 = """
Hello:
      欢迎大家
      大家好
"""  #三引号定义（多行字符串）



print(s1)
print(s2)
print(s3)

#定义字符串
#转义字符\'    \"   \n  \t
#\'--->单引号-->表示单引号'
#\"--->双引号--->表示双引号"
#\n--->换行符--->开始新的一行
#\t--->制表符--->增加缩进，缩进一个制表符（ta b）的大小
me = 'It\'s very good'
print(me)

me1 = 'Hello \n Good morning'
print(me1)