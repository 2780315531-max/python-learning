"""
循环嵌套：根据输入的长方形长度m，宽度n，打印一个长方形；
如下：是一个长度为5，宽度为3的长方形：
            * * * * *
            * * * * *
            * * * * *
         print("*"):自带换行效果，每一次执行都会输出新的一行中
         print("*",end="")：end表示每一次输出以什么结束；默认\n表换行
        `ange(n)： 会生成 `0,1,2,...,n-1` 一共 `n` 个数字
        for j in ...：循环执行 n 次，每一次循环代表一行

"""

#1.接收键盘录入m,n
m = int(input("请输入长方形的长度:"))
n = int(input("请输入长方形的宽度:"))
#2.打印长方形
for j in range(n):  #控制行
    for i in range(m):      #控制列
        print("*",end="  ")
    print()


#嵌套循环案例：打印99乘法表
for i in range(1,10):   #外层循环-控制行
    for j in range(1,i+1):#内层循环-控制列
        print(f"{j} x {i} = {j * i}", end = "\t")
    print()


#练习1:根据输入的直角边的边长，打印等腰直角三角形
b = int(input("请输入直角边边长:"))

for j in range(b):#外层循环：控制一共n行，j代表当前是第几行（从0开始)
    for i in range(j+1):## 内层循环：当前这一行要打印 j+1 个 *
        print("*",end=" ")
    #一行打完，换行
    print()

#练习2.根据输入的数字，打印对应的金字塔
a = int(input("请输入数字:"))
for j in range(a):  # 第j行，要打印 1 ~ j+1
    for i in range(j+1):# i从0开始，所以打印 i+1
        print(i+1,end=" ")
    print()
"""
j in range(a)`：一共打印 a 行，j=0 是第 1 行，j=1 是第 2 行……
i in range(j+1)`：第 j 行，循环 `j+1` 次
 j=0 → 循环 1 次，i=0 → 打印 `0+1=1`
  j=1 → 循环 2 次，i=0、1 → 打印 `1 2`
  j=2 → 循环 3 次，i=0、1、2 → 打印 `1 2 3`
- `print(i + 1, end=" ")`：打印数字，不换行，数字之间空格隔开
- 最后的 `print()`：一行打完，换行
"""

#练习3.打印国际象棋
# 8行8列棋盘
for j in range(8):   # j 代表行，0~7
    for i in range(8): # i 代表列，0~7
        if (j + i) % 2 == 0:
            print("■", end=" ")
        else:
            print("□", end=" ")
    print()  # 一行结束换行
"""
1. `for j in range(8)`：外层循环，一共 8 行（棋盘 8 行）
2. `for i in range(8)`：内层循环，一行里面 8 个格子（8 列）
3. `(j + i) % 2 == 0`
   - `%` 是取余，判断和是不是偶数
   - 偶数 → 打印黑块 `■`
   - 奇数 → 打印白块 `□`
4. `end=" "`：打印完方块不换行，空格隔开
5. 内层循环结束后的 `print()`：当前一行全部打完，换行，开始下一行
"""