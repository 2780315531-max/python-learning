#########逻辑运算符：and  or  not##########
#案例1：要求输入一个整数，判断这个数是否在10到20之间---->在：True  不在：False
num = int(input("请输入一个整数:"))#input表示输入的内容为字符串类型，int(..)将字符串转为整数类型
print(f"{num}是否在10到20之间:",num >= 10 and num <= 20) #and连接的条件是并且的关系，两个条件 
print(f"{num}是否在10到20之间:",10 <= num <= 20) #python中可以直接写成这样，简易比较


#案例2:：要求输入一个整数，判断这个数是否不在10到20之间
n = int(input("请输入一个整数:"))
print(f"{n}是否不在10到20之间:",n < 10 or n > 20) #or连接的条件是或者的关系，两个条件只要有一个成立就为True ,结果为True；全部不成立才为False



#逻辑运算符运用场景：B站登入方式
#逻辑运算符用于连接多个布尔表达式（True/False），最终结果为True或False
#and（并且，同时成立）
#or（或者，至少有一个成立）
#not（非，取反）
