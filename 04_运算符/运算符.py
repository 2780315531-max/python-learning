#算术运算符：+ - / *   //   %   **
print("10 + 4 =",10 + 4)
print("10 - 4 =",10 - 4)
print("10 * 4 =",10 * 4)
print("10 / 4 =",10 / 4)
print("10 // 4 =",10 // 4) #整除（结果为整数）
print("10 % 4 =",10 % 4)  #取余/求模
print("10 ** 4 =",10 ** 4) # 10的4次方，幂指数

#算术运算符的优先级---> ** -->*    /  //    %  -->+ -
print("0.1 + 10 / 4 ** 3 =", 0.1 + 10 / 4 ** 3)

